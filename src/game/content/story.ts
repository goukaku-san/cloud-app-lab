/**
 * 章と自己申告に対応する物語を返す。
 * dayIndex は帰還した日数（1 始まり）。最終章（14）の翌日以降はエピローグを巡回する。
 */
export function storyFor(chapter: number, report: SelfReport, dayIndex: number): StoryEntry {
  if (report === "skip") return SKIP_STORY;
  if (dayIndex > STORY_CHAPTERS.length) {
    const idx = (dayIndex - STORY_CHAPTERS.length - 1) % EPILOGUE.length;
    return EPILOGUE[idx][report];
  }
  const ch = STORY_CHAPTERS.find((c) => c.chapter === chapter) ?? STORY_CHAPTERS[0];
  return ch.stories[report];
}
